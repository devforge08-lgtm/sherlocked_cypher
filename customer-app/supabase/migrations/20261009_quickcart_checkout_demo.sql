BEGIN;

create extension if not exists pgcrypto;

-- If this project has the singular public.address table but no public.addresses,
-- rename it so the frontend and this migration use one canonical table without
-- throwing away saved address rows. PostgreSQL preserves existing table data/FKs.
DO $$
BEGIN
  IF to_regclass('public.addresses') IS NULL
     AND to_regclass('public.address') IS NOT NULL THEN
    ALTER TABLE public.address RENAME TO addresses;
  END IF;
END;
$$;

-- New installs use BIGINT IDs. If addresses already exists, its existing id type
-- is preserved rather than changed.
create table if not exists public.addresses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null default 'Home',
  recipient_name text,
  phone text,
  address_line text,
  latitude double precision,
  longitude double precision,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

-- Add checkout fields to an existing addresses table without changing its id type.
alter table public.addresses add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.addresses add column if not exists label text not null default 'Home';
alter table public.addresses add column if not exists recipient_name text;
alter table public.addresses add column if not exists phone text;
alter table public.addresses add column if not exists address_line text;
alter table public.addresses add column if not exists latitude double precision;
alter table public.addresses add column if not exists longitude double precision;
alter table public.addresses add column if not exists is_default boolean not null default false;
alter table public.addresses add column if not exists created_at timestamptz not null default now();

-- Ensure an existing BIGINT id can be generated automatically on address inserts
-- when that column previously had neither IDENTITY nor a default/sequence.
DO $$
DECLARE
  v_type text;
  v_identity text;
  v_default text;
  v_seq text;
  v_max bigint;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod), a.attidentity, pg_get_expr(d.adbin, d.adrelid)
    INTO v_type, v_identity, v_default
  FROM pg_attribute a
  LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
  WHERE a.attrelid = 'public.addresses'::regclass
    AND a.attname = 'id'
    AND a.attnum > 0
    AND NOT a.attisdropped;

  IF v_type = 'bigint' AND coalesce(v_identity, '') = '' AND v_default IS NULL THEN
    ALTER TABLE public.addresses ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    v_seq := pg_get_serial_sequence('public.addresses', 'id');
    IF v_seq IS NOT NULL THEN
      SELECT coalesce(max(id), 0) INTO v_max FROM public.addresses;
      PERFORM setval(v_seq::regclass, greatest(v_max, 1), v_max >= 1);
    END IF;
  END IF;
END;
$$;

-- Create orders with address_id matching the actual public.addresses.id type.
-- If orders already exists, keep the table and its existing rows.
DO $$
DECLARE
  v_address_type text;
  v_address_type_oid oid;
  v_order_type_oid oid;
  v_address_attnum smallint;
  v_fk record;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod), a.atttypid
    INTO v_address_type, v_address_type_oid
  FROM pg_attribute a
  WHERE a.attrelid = 'public.addresses'::regclass
    AND a.attname = 'id'
    AND a.attnum > 0
    AND NOT a.attisdropped;

  IF v_address_type IS NULL THEN
    RAISE EXCEPTION 'Could not determine type of public.addresses.id';
  END IF;

  IF to_regclass('public.orders') IS NULL THEN
    EXECUTE format($create_orders$
      CREATE TABLE public.orders (
        id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
        order_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
        user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
        address_id %s,
        delivery_address text NOT NULL,
        status text NOT NULL DEFAULT 'pending_payment',
        payment_status text NOT NULL DEFAULT 'pending',
        payment_method text NOT NULL DEFAULT 'demo_qr',
        payment_reference text,
        subtotal numeric(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
        delivery_fee numeric(12,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
        total_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
        created_at timestamptz NOT NULL DEFAULT now(),
        updated_at timestamptz NOT NULL DEFAULT now()
      )
    $create_orders$, v_address_type);
  ELSE
    -- Add address_id using the parent key type if it is absent.
    IF NOT EXISTS (
      SELECT 1 FROM pg_attribute
      WHERE attrelid = 'public.orders'::regclass
        AND attname = 'address_id'
        AND attnum > 0 AND NOT attisdropped
    ) THEN
      EXECUTE format('ALTER TABLE public.orders ADD COLUMN address_id %s', v_address_type);
    ELSE
      SELECT a.atttypid INTO v_order_type_oid
      FROM pg_attribute a
      WHERE a.attrelid = 'public.orders'::regclass
        AND a.attname = 'address_id'
        AND a.attnum > 0 AND NOT a.attisdropped;

      IF v_order_type_oid IS DISTINCT FROM v_address_type_oid THEN
        -- Existing UUID address references cannot be translated to BIGINT IDs.
        -- Drop their FK(s), then retain orders but clear only the incompatible refs.
        FOR v_fk IN
          SELECT c.conname
          FROM pg_constraint c
          JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attname = 'address_id'
          WHERE c.conrelid = 'public.orders'::regclass
            AND c.contype = 'f'
            AND a.attnum = ANY(c.conkey)
        LOOP
          EXECUTE format('ALTER TABLE public.orders DROP CONSTRAINT %I', v_fk.conname);
        END LOOP;
        EXECUTE format('ALTER TABLE public.orders ALTER COLUMN address_id TYPE %s USING NULL', v_address_type);
      END IF;
    END IF;
  END IF;

  -- Add common checkout columns when orders was created by an earlier schema.
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE;
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS order_number bigint GENERATED BY DEFAULT AS IDENTITY;
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS delivery_address text;
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'pending_payment';
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS payment_status text NOT NULL DEFAULT 'pending';
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS payment_method text NOT NULL DEFAULT 'demo_qr';
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS payment_reference text;
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS subtotal numeric(12,2) NOT NULL DEFAULT 0;
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS delivery_fee numeric(12,2) NOT NULL DEFAULT 0;
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS total_amount numeric(12,2) NOT NULL DEFAULT 0;
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
  ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

  -- Drop any existing FK involving orders.address_id, then create one correct FK.
  SELECT a.attnum INTO v_address_attnum
  FROM pg_attribute a
  WHERE a.attrelid = 'public.orders'::regclass
    AND a.attname = 'address_id'
    AND a.attnum > 0 AND NOT a.attisdropped;

  FOR v_fk IN
    SELECT c.conname
    FROM pg_constraint c
    WHERE c.conrelid = 'public.orders'::regclass
      AND c.contype = 'f'
      AND v_address_attnum = ANY(c.conkey)
  LOOP
    EXECUTE format('ALTER TABLE public.orders DROP CONSTRAINT %I', v_fk.conname);
  END LOOP;

  -- Clear only broken/legacy links that don't reference an existing address row.
  UPDATE public.orders o
    SET address_id = NULL
  WHERE o.address_id IS NOT NULL
    AND NOT EXISTS (
      SELECT 1 FROM public.addresses a WHERE a.id = o.address_id
    );

  ALTER TABLE public.orders
    ADD CONSTRAINT orders_address_id_fkey
    FOREIGN KEY (address_id) REFERENCES public.addresses(id) ON DELETE SET NULL;
END;
$$;

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

alter table public.order_items add column if not exists product_id bigint;
alter table public.order_items add column if not exists product_name text;
alter table public.order_items add column if not exists quantity integer;
alter table public.order_items add column if not exists unit_price numeric(12,2);
alter table public.order_items add column if not exists line_total numeric(12,2);
alter table public.order_items add column if not exists created_at timestamptz not null default now();

create index if not exists addresses_user_id_idx on public.addresses(user_id);
create index if not exists orders_user_id_created_at_idx on public.orders(user_id, created_at desc);
create index if not exists order_items_order_id_idx on public.order_items(order_id);

alter table public.addresses enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Users can view their own addresses" on public.addresses;
create policy "Users can view their own addresses" on public.addresses
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Users can add their own addresses" on public.addresses;
create policy "Users can add their own addresses" on public.addresses
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users can update their own addresses" on public.addresses;
create policy "Users can update their own addresses" on public.addresses
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users can delete their own addresses" on public.addresses;
create policy "Users can delete their own addresses" on public.addresses
  for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can view their own orders" on public.orders;
create policy "Users can view their own orders" on public.orders
  for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Users can create their own orders" on public.orders;
create policy "Users can create their own orders" on public.orders
  for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users can update their own orders" on public.orders;
create policy "Users can update their own orders" on public.orders
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users can delete their own orders" on public.orders;
create policy "Users can delete their own orders" on public.orders
  for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "Users can view items from their own orders" on public.order_items;
create policy "Users can view items from their own orders" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id and o.user_id = (select auth.uid())
  ));
drop policy if exists "Users can add items to their own orders" on public.order_items;
create policy "Users can add items to their own orders" on public.order_items
  for insert to authenticated
  with check (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id and o.user_id = (select auth.uid())
  ));

COMMIT;

